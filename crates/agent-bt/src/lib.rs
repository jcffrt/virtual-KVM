//! RawKVM Bluetooth bridge: presents a receiver of the hub to one PC as a
//! classic (BR/EDR) Bluetooth HID keyboard and mouse. See
//! docs/fase7-plan.md and docs/adr/0033.
//!
//! The modules here are plain data (SDP record, HIDP transactions) and
//! build everywhere; BlueZ is only used by the Linux binaries.

pub mod hidp;
pub mod sdp;

/// Keyboard (report ID 1, boot layout with the LED output report) and
/// mouse (report ID 2: three buttons, X, Y, wheel): the fixed descriptor of
/// the proof of concept.
pub const POC_DESCRIPTOR: &[u8] = &[
    // Keyboard
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01, //
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81,
    0x02, // modifiers
    0x95, 0x01, 0x75, 0x08, 0x81, 0x01, // reserved
    0x95, 0x05, 0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02, // LEDs
    0x95, 0x01, 0x75, 0x03, 0x91, 0x01, // LED padding
    0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81,
    0x00, // keys
    0xC0, //
    // Mouse
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0x09, 0x01, 0xA1, 0x00, //
    0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81,
    0x02, // buttons
    0x95, 0x01, 0x75, 0x05, 0x81, 0x01, // padding
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03,
    0x81, 0x06, // X, Y, wheel (relative)
    0xC0, 0xC0,
];

pub const POC_KEYBOARD_ID: u8 = 1;
pub const POC_MOUSE_ID: u8 = 2;

#[cfg(test)]
mod tests {
    use super::*;
    use proto::descriptor::DescriptorInfo;

    #[test]
    fn poc_descriptor_parses_as_keyboard_and_mouse() {
        let info = DescriptorInfo::parse(POC_DESCRIPTOR);
        assert!(info.uses_report_ids);
        assert!(info.is_keyboard() && info.is_mouse());
        let inputs: Vec<(Option<u8>, usize)> =
            info.inputs.iter().map(|r| (r.report_id, r.len)).collect();
        assert_eq!(inputs, [(Some(1), 8), (Some(2), 4)]);
        let outputs: Vec<(Option<u8>, usize)> =
            info.outputs.iter().map(|r| (r.report_id, r.len)).collect();
        assert_eq!(outputs, [(Some(1), 1)]);
    }
}
